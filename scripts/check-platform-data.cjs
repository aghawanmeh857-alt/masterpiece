const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const {mergeContent}=require('../assets/platform-data.js');
const seeds=[{id:'job1',title:'Existing',status:'published',budget:450}];
assert.equal(mergeContent(seeds,[{id:'job1',title:'Edited'}])[0].budget,450);
assert.equal(seeds[0].title,'Existing');
assert.equal(mergeContent(seeds,[{id:'job1',status:'paused'}]).length,0);
assert.equal(mergeContent(seeds,[],['job1']).length,0);
const app={companyJobs:[],companyWorkspace:{content:[]}};
vm.runInNewContext(fs.readFileSync('assets/platform-data.js','utf8'),{window:{OfoqFrontend:app}});
app.companyJobs.push({id:'company1',title:'Designer',company:'My company',category:'design',description:'Design a product',status:'published',requirements:['Figma'],offer:'900 JOD'});
let rows=app.contentFor('jobs',seeds);
assert.equal(rows.length,2);
assert.equal(rows.find(row=>row.id==='company1').company,'My company');
assert.deepEqual(rows.find(row=>row.id==='company1').requirements,['Figma']);
assert.equal(app.contentFor('jobs',seeds).find(row=>row.id==='company1').title,'Designer','List and detail resolve the same current content');
app.companyJobs[0].status='paused';assert.equal(app.contentFor('jobs',seeds).length,1);
app.companyJobs[0].status='published';assert.equal(app.contentFor('jobs',seeds).length,2);
app.publishContent('jobs',{id:'company1',title:'Reviewed by admin',status:'published'});
assert.equal(app.contentFor('jobs',seeds).find(row=>row.id==='company1').title,'Reviewed by admin','Admin changes take precedence over company content');
app.publishContent('jobs',{id:'job1',title:'Admin edit',status:'published'});
assert.equal(app.contentFor('jobs',seeds).find(row=>row.id==='job1').title,'Admin edit');
app.removedContent={jobs:['job1']};assert.equal(app.contentFor('jobs',seeds).some(row=>row.id==='job1'),false);
app.companyWorkspace.content.push({id:'course1',type:'course',title:'Training',category:'التطوير',syllabus:'Intro\nPractice',status:'published',hours:8});
assert.equal(app.contentFor('courses',[]).length,0,'Company cannot publish admin-owned courses');
app.publishContent('courses',{id:'course1',title:'Admin training',category:'التطوير',syllabus:'Intro\nPractice',status:'published',hours:8,publisherRole:'admin'});
rows=app.contentFor('courses',[]);
assert.equal(rows[0].category,'development');assert.equal(rows[0].syllabus.length,2);assert.equal(rows[0].hours,8);
app.publishContent('courses',{id:'course1',status:'draft'});assert.equal(app.contentFor('courses',[]).length,0);
app.companyInternships=[{id:'intern-new',title:'Company internship',status:'published',details:['Publisher details']}];
assert.equal(app.contentFor('internships',[])[0].details[0],'Publisher details');
assert.equal(fs.readFileSync('hero/userHero.html','utf8').match(/class="chapter"/g).length,6,'Keep all six scene sections');
assert(fs.readFileSync('hero/room-sections.js','utf8').includes('خدمات المنصة'));
assert(fs.readFileSync('hero/userHero.js','utf8').includes('renderRoomSections'));
assert(fs.readFileSync('hero/userHero.js','utf8').includes('texture.repeat.set(1, 1)'));
console.log('Passed: shared content, company publish/pause/re-publish, list/detail parity, admin edits/removal, course syllabus normalization, original tour and uncropped vector mark.');
