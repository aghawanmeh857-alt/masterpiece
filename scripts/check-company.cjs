const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createWorkspace } = require('../company/dashboard.js');
const model = createWorkspace();
const event = { ...model.find('e1'), title: 'فعالية اختبار', capacity: 2, status: 'draft' };
const created = model.save(event);
assert.notEqual(created.id, 'e1');
assert.equal(model.find(created.id).status, 'draft');
model.setPublication(created.id, 'published');
model.setPublication(created.id, 'paused');
model.setPublication(created.id, 'archived');
model.setPublication(created.id, 'published');
assert.equal(model.find(created.id).status, 'published');
assert.throws(() => model.setPublication(created.id, 'invalid'));
model.save({ ...created, title: 'عنوان محدّث' }, created.id);
assert.equal(model.find(created.id).title, 'عنوان محدّث');
const course = model.save({ ...model.find('c1'), title: 'درس جديد', syllabus: 'مقدمة\nتطبيق عملي' });
assert.equal(course.type, 'course');
assert.equal(course.syllabus.split('\n').length, 2);
assert.throws(() => model.save({ ...course, video: 'javascript:alert(1)' }));
assert.throws(() => model.save({ ...course, hours: 0 }));
assert.throws(() => model.save({ ...event, eventDate: 'invalid' }));
assert.throws(() => model.save({ ...event, title: '  ' }));
assert.throws(() => model.save({ ...event, capacity: 1.5 }));
model.review('a1', 'accepted');
assert.equal(model.applications.find(item => item.id === 'a1').status, 'accepted');
assert.throws(() => model.save({ ...model.find('e1'), capacity: 1 }, 'e1'), /المقبولين/);
model.review('a1', 'rejected');
assert.equal(model.applications.find(item => item.id === 'a1').status, 'rejected');
model.setPublication('e1', 'archived');
assert.throws(() => model.review('a1', 'accepted'), /تفعيل/);
model.setPublication('e1', 'published');
model.save({ ...model.find('e1'), capacity: 1 }, 'e1');
assert.throws(() => model.review('a1', 'accepted'), /المقاعد/);
model.review('a3', 'rejected');
model.review('a1', 'accepted');
assert.equal(model.applications.find(item => item.id === 'a1').status, 'accepted');
assert.equal(createWorkspace().find('e1').capacity, 30, 'A new visit starts with independent demo data');
const html = fs.readFileSync(require.resolve('../company/dashboard.html'), 'utf8');
const script = fs.readFileSync(require.resolve('../company/dashboard.js'), 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(match => match[1]);
assert.equal(new Set(ids).size, ids.length, 'HTML IDs must be unique');
for (const [, id] of script.matchAll(/\$\('([^']+)'\)/g)) assert(ids.includes(id), `Missing element: ${id}`);
console.log('Passed: company content create/edit, publication states, course lessons, applicant decisions, seat limits, archive rules, validation and DOM references.');
